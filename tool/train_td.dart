// TD(0) self-play training for NnEval.
//
//   dart compile exe tool/train_td.dart -o build/train
//   build/train --games 200000 --hidden 40 [--resume build/nn.txt]
//
// Writes build/nn.txt (flat weights) periodically and, at the end,
// lib/core/ai/nn_weights.dart.
// ignore_for_file: avoid_print
import 'dart:io';
import 'dart:math' as math;

import 'package:haftnard/core/ai/nn_eval.dart';
import 'package:haftnard/core/rules/board.dart';
import 'package:haftnard/core/rules/move_gen.dart';
import 'package:haftnard/core/rules/types.dart';

void main(List<String> args) {
  String arg(String k, String d) {
    final i = args.indexOf(k);
    return i >= 0 && i + 1 < args.length ? args[i + 1] : d;
  }

  final games = int.parse(arg('--games', '100000'));
  final hidden = int.parse(arg('--hidden', '40'));
  final resume = arg('--resume', '');
  final net = resume.isNotEmpty && File(resume).existsSync()
      ? NnEval.fromFlat(
          File(resume)
              .readAsStringSync()
              .trim()
              .split(',')
              .map(double.parse)
              .toList(),
          hidden,
        )
      : NnEval.random(hidden, 1);
  final rng = math.Random(42);
  final sw = Stopwatch()..start();
  var turnsTotal = 0;
  for (var g = 0; g < games; g++) {
    final alpha = games > 1
        ? 0.1 * math.pow(0.1, g / games).toDouble() + 0.01
        : 0.05;
    var board = Board.initial();
    var side = rng.nextBool() ? Side.white : Side.black;
    // Last position each side produced (its own frame), awaiting a target.
    final pending = <Side, (List<int>, List<int>)?>{
      Side.white: null,
      Side.black: null,
    };
    for (var turn = 0; turn < 500; turn++) {
      final a = rng.nextInt(6) + 1;
      final b = rng.nextInt(6) + 1;
      final dice = a == b ? [a, a, a, a] : [a, b];
      final sim = TurnSim.fromBoard(board, side);
      final plays = MoveGen.allPlays(sim, dice);
      var best = plays.first;
      var bestV = -1.0;
      for (final p in plays) {
        if (p.result.mine[0] == 15) {
          best = p;
          bestV = 2;
          break;
        }
        final v = net.winProb(p.result.mine, p.result.theirs);
        if (v > bestV) {
          bestV = v;
          best = p;
        }
      }
      final mine = List<int>.of(best.result.mine);
      final theirs = List<int>.of(best.result.theirs);
      // The opponent's previous position: its value equals 1 - my value now.
      final opp = pending[side.opponent];
      if (opp != null) {
        final target = mine[0] == 15 ? 0.0 : 1 - net.winProb(mine, theirs);
        net.train(opp.$1, opp.$2, target, alpha);
      }
      if (mine[0] == 15) {
        net.train(mine, theirs, 1, alpha);
        break;
      }
      pending[side] = (mine, theirs);
      board = best.result.toBoard(side);
      side = side.opponent;
      turnsTotal++;
    }
    if ((g + 1) % 5000 == 0) {
      File('build/nn.txt').writeAsStringSync(net.toFlat().join(','));
      print(
        '${g + 1} games, ${sw.elapsed.inSeconds}s, ${(turnsTotal / (g + 1)).toStringAsFixed(1)} turns/game, alpha=${alpha.toStringAsFixed(3)}',
      );
    }
  }
  File('build/nn.txt').writeAsStringSync(net.toFlat().join(','));
  writeDart(net, hidden);
  print('done in ${sw.elapsed.inSeconds}s');
}

void writeDart(NnEval net, int hidden) {
  final flat = net.toFlat();
  final b = StringBuffer()
    ..writeln('// GENERATED by tool/train_td.dart — do not edit.')
    ..writeln(
      '// TD(0) self-play value network weights (${flat.length} values).',
    )
    ..writeln()
    ..writeln('const int kNnHidden = $hidden;')
    ..writeln()
    ..writeln('const List<double> kNnWeights = [');
  for (var i = 0; i < flat.length; i += 8) {
    b.writeln(
      '  ${flat.sublist(i, math.min(flat.length, i + 8)).map((v) => v.toStringAsFixed(5)).join(', ')},',
    );
  }
  b.writeln('];');
  File('lib/core/ai/nn_weights.dart').writeAsStringSync(b.toString());
}
