import 'package:haftnard/meta/profile.dart';

/// Achievement definitions. Condition functions read [Stats]/[Profile].
class Achievement {
  const Achievement({
    required this.id,
    required this.nameEn,
    required this.nameFa,
    required this.descEn,
    required this.descFa,
    required this.gems,
    required this.check,
    this.icon = 0,
  });

  final String id;
  final String nameEn;
  final String nameFa;
  final String descEn;
  final String descFa;
  final int gems;
  final bool Function(Profile p) check;
  final int icon;

  String name(String lang) => lang == 'fa' ? nameFa : nameEn;
  String desc(String lang) => lang == 'fa' ? descFa : descEn;
}

